import type { Ingredient, IngredientKind } from '../types';

/**
 * The ingredients Cooking converts through (ADR 0021): the baking staples to start, each with the
 * weight of one US customary cup as USDA FoodData Central measures it (SR Legacy), read from the
 * food's own portions and checked again blind (docs/research/cooking-1.md). Where USDA weighs a
 * smaller measure only, the cup is that measure times how many make a cup (48 teaspoons, 16
 * tablespoons). Densities are measured, never exact: the table marks what crosses with ≈.
 */

/** FoodData Central's citation for one food and the portion read from it. */
function fdc(id: number, food: string, portion: string): string {
  return `USDA FoodData Central ${id} (SR Legacy): ${food}; ${portion}`;
}

